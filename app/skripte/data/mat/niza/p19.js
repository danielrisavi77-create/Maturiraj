  if (K <= 0 || p < 0 || n <= 0) {
    res.classList.add('show');
    res.innerHTML = '<div style="color:var(--red)">K, n > 0, p ≥ 0.</div>';
    return;
  }
  
  const q = 1 + p / 100;
  const qn = Math.pow(q, n);
